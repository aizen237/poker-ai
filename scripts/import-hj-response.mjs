// Reproduce the two-node source snapshot. No live/network dependency at runtime.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
const commit = '590b8f65a9728a99ab8fb5d7a4ec9dc40a65225e';
const base = `https://raw.githubusercontent.com/jensbaagaard/poker-practice/${commit}/data/openSourcePokerData/`;
const response = await fetch(base + 'Cash_100_GTO.json');
if (!response.ok) throw new Error(`Source download failed: ${response.status}`);
const bytes = Buffer.from(await response.arrayBuffer());
const blob = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
if (blob !== '3102a91612bda6ffe8b8185ed1ecca07d089dcce') throw new Error('Pinned source blob mismatch');
const data = JSON.parse(bytes.toString('utf8'));
const nodes = { '3BetHJvsLJ': data['3BetHJvsLJ'], CallHJvsLJ: data.CallHJvsLJ };
for (const node of Object.values(nodes)) {
  if (!node || Object.keys(node).length !== 169) throw new Error('Incomplete pinned source');
}
const target = new URL('../packages/ai-core/src/data/hjResponseSource.ts', import.meta.url);
const generated = `// Generated by scripts/import-hj-response.mjs; do not edit frequencies.\n` +
  `// Commit ${commit}; Git blob ${blob}.\n` +
  `// Original action nodes only. Documented fold complement and sizing: HJ_RESPONSE_COVERAGE.md.\n` +
  `export const hjResponseSource = ${JSON.stringify(nodes, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== generated) throw new Error('Local source snapshot differs from pinned upstream');
} else await writeFile(target, generated);
console.log(`Verified ${blob}; two explicit 169-hand nodes ${process.argv.includes('--check') ? 'match the local snapshot' : 'extracted'}.`);
